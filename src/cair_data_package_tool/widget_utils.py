def multi_path_box(i,multi_path_box_type,self):
    # multi_path_box_type is one of: customBulkAddFilePaths,customBulkAddMultiLikeFilePaths
    prop = i["prop"]
    prop_title = self.schema["properties"][prop]["title"]
    print(prop_title)
    if i.get("buttonText"):
        button_text = i["buttonText"]
    else:
        if multi_path_box_type == "customBulkAddFilePaths":
            button_text = "Bulk add files for: " + prop_title 
        elif multi_path_box_type == "customBulkAddMultiLikeFilePaths":
            button_text = "Add Multiple \'like\' file paths for: " + prop_title
    if i.get("labelText"):
        label_text = i["labelText"]
    else:
        if multi_path_box_type == "customBulkAddFilePaths":
            label_text = \
                "To bulk add files for the " + \
                    prop_title + \
                        " field <b>drag and drop file paths right here</b>. If you intend to add one or just a few files for " + \
                            prop_title + \
                                ", you can drag and drop them here or browse to each file (one file at a time) using the " + \
                                    prop_title + \
                                        " field in the form below."
        elif multi_path_box_type == "customBulkAddMultiLikeFilePaths":
            label_text = \
                "To add multiple \'like\' files for the " + \
                    prop_title + \
                        " field <b>drag and drop file paths right here</b>. If you intend to add one file for " + \
                            prop_title + \
                                ", use the " + \
                                    prop_title + \
                                        " field in the form below to browse directly to the single file path."

    # Create the button, label, and drag&drop file list box dynamically
    btn = QtWidgets.QPushButton(text=button_text,parent=self)
    if multi_path_box_type == "customBulkAddFilePaths":
        btn_tt_text = "bulk add files"
    elif multi_path_box_type == "customBulkAddMultiLikeFilePaths":
        btn_tt_text = "add multi \'like\' files"
    btn.setToolTip("Click this button to open a drag and drop box to " + btn_tt_text + " for the " + prop_title + " field.") # add tooltip to button bc by default the label and add_files_box will be hidden so this will give the user some guidance as to what 
    lbl = QtWidgets.QLabel(text=label_text,parent=self)

    # create drag and drop window for multiple file dependencies addition
    add_files_box = ListboxWidget(parent=self)
    add_files_box_model = add_files_box.model()
    add_files_items = []
    add_files_items_programmatic_update = False

    # Store the items in dynamic_customBulkAddFilePaths dictionary
    if multi_path_box_type == "customBulkAddFilePaths":
        save_dict = self.dynamic_customBulkAddFilePaths
    elif multi_path_box_type == "customBulkAddMultiLikeFilePaths":
        save_dict = self.dynamic_customBulkAddMultiLikeFilePaths

    save_dict.setdefault(prop, {})

    if multi_path_box_type == "customBulkAddMultiLikeFilePaths":
        save_dict[prop]["collect_property"] = i["collectProp"]
        save_dict[prop]["file_name_convention_property"] = i["fileNameConventionProp"]
        save_dict[prop]["file_description_property"] = i["fileDescriptionProp"]

        lbl_applyNameConvention = QtWidgets.QLabel(text="To apply a naming convention when adding multiple 'like' resources that share a naming convention, <b>add your naming convention in the Name Convention field in the form below</b>, then come back and <b>click the Apply Name Convention button right here</b> to apply. This will autogenerate a minimal description based on the naming convention for each of your 'like' files." + "\n\n" + "e.g." + "\n" + "Name Convention: subject_{subject ID}_day_{date of data collection in YYYYMMDD})" + "\n" + "Example File Name: subject_A1_day_20230607)" + "\n" + "Autogenerated File Description: subject ID: A1, date of data collection in YYYYMMDD: 20230607)",parent=self)
        lbl_applyNameConvention.setSizePolicy(QtWidgets.QSizePolicy.Preferred, QtWidgets.QSizePolicy.Expanding)
        lbl_applyNameConvention.setWordWrap(True)

        # create button to apply naming convention for multiple like resources
        btn_applyNameConvention = QtWidgets.QPushButton(text="Apply Name Convention",parent=self)
        btn_applyNameConvention.clicked.connect(apply_name_convention)

        save_dict[prop]["btn_applyNameConvention"] = btn_applyNameConvention
        save_dict[prop]["lbl_applyNameConvention"] = lbl_applyNameConvention

    save_dict[prop]["btn"] = btn
    save_dict[prop]["lbl"] = lbl
    
    save_dict[prop]["add_files_box"] = add_files_box
    save_dict[prop]["add_files_box_model"] = add_files_box_model
    save_dict[prop]["add_files_items"] = add_files_items
    save_dict[prop]["add_files_items_programmatic_update"] = add_files_items_programmatic_update

    # when button is clicked hide/show the bulk add file box and box label
    btn.clicked.connect(
        lambda checked, property=prop, label=lbl, add_files_box=add_files_box: toggle_add_file_box_visibility(property,label,add_files_box,self)
    )
    
    # set sizing and word wrap for add file box label
    lbl.setSizePolicy(
        QtWidgets.QSizePolicy.Preferred, QtWidgets.QSizePolicy.Expanding
    )
    lbl.setWordWrap(True)

    
    # when user adds or deletes files via the add files drop box, update the items list
    add_files_box_model.rowsInserted.connect(
        lambda parent, first, last, property=prop: update_add_files_list_from_box(property=property,multi_path_box_type=multi_path_box_type,self=self)
    )
    add_files_box_model.rowsRemoved.connect(
        lambda parent, first, last, property=prop: update_add_files_list_from_box(property=property,multi_path_box_type=multi_path_box_type,self=self)
    )
    
    self.vbox.addWidget(btn)
    self.vbox.addWidget(lbl)
    self.vbox.addWidget(add_files_box)
    
    lbl.hide()
    add_files_box.hide()

    if multi_path_box_type == "customBulkAddFilePaths":
        # add in update of files in add_files_box if user add/deletes using the property's form field widget
        # instead of the drag and drop box
        self.formWidgetList[self.formWidgetNameList.index(prop)].on_changed.connect(
            lambda state, property=prop: update_add_files_list_from_form_field(property,self)
        )
        # install event filter on the corresponding form field widget - event filter watches for if/when 
        # the form field widget changes from shown to hidden or vice versa and applies this same action to the
        # corresponding bulk add files widgets (button, label, add_files_box)
        self.formWidgetList[self.formWidgetNameList.index(prop)].installEventFilter(self)

def update_add_files_list_from_form_field(property,self):

    property = property
    print("property in update items from form field fx: ",property) 
    print("form widget state: ",self.form.widget.state[property])
    print("add_files_items from dict: ",self.dynamic_customBulkAddFilePaths[property]["add_files_items"])

    # if user just added a new spot to add a file (no new file added yet), return
    current_form_widget_state = self.form.widget.state[property]
    current_form_widget_state_remove_empty = [i for i in current_form_widget_state if i]
    if current_form_widget_state != current_form_widget_state_remove_empty:
        return

    # if user added a file or deleted a file via the form field, 
    # 1) update the add_files_items in dict
    # 2) update the items listed in the add_files_box
    
    # 1)
    self.dynamic_customBulkAddFilePaths[property]["add_files_items"] = current_form_widget_state

    # 2) 
    # set to programmatic update
    self.dynamic_customBulkAddFilePaths[property]["add_files_items_programmatic_update"] = True
    
    self.dynamic_customBulkAddFilePaths[property]["add_files_box"].clear()
    self.dynamic_customBulkAddFilePaths[property]["add_files_box"].addItems(current_form_widget_state)

def update_add_files_list_from_box(property,multi_path_box_type,self):
     # multi_path_box_type is one of: customBulkAddFilePaths,customBulkAddMultiLikeFilePaths  
    property = property
    print("property in update items from box fx: ",property) 

    # Store the items in dynamic_customBulkAddFilePaths dictionary
    if multi_path_box_type == "customBulkAddFilePaths":
        save_dict = self.dynamic_customBulkAddFilePaths
    elif multi_path_box_type == "customBulkAddMultiLikeFilePaths":
        save_dict = self.dynamic_customBulkAddMultiLikeFilePaths

    # if files in box are being updated programmatically, return         
    if save_dict[property]["add_files_items_programmatic_update"]:
        save_dict[property]["add_files_items_programmatic_update"] = False
        return

    add_files_box = save_dict[property]["add_files_box"]

    # store old items list
    oldLength = None
    if save_dict[property]["add_files_items"]:
        oldLength = len(save_dict[property]["add_files_items"])
        oldItems = save_dict[property]["add_files_items"]

        print(oldItems)
        print(oldLength)

    # update items list with what files/folders are actually in the box now
    updated_items_list = [add_files_box.item(x).text() for x in range(add_files_box.count())]
    
    # if there are any directories in the box now, get the files in the directory and add those to items list, replacing the name of the directory in the items list 
    refactored_items_list = []
    for i in updated_items_list:
        myPath = Path(i).resolve()
        if myPath.is_dir():
            # only unpack one level - i.e. if the dir has subdirs, the files in subdirs will not be unpacked via this method
            myFiles = [str(f) for f in myPath.iterdir() if f.is_file()]
            refactored_items_list.extend(myFiles)
        else:
            refactored_items_list.append(str(myPath))

    # update dictionary items list whether refactor to account for directories was necessary or not
    save_dict[property]["add_files_items"] = refactored_items_list
    
    if updated_items_list != refactored_items_list:
        save_dict[property]["add_files_items_programmatic_update"] = True

        save_dict[property]["add_files_box"].clear()
        save_dict[property]["add_files_box"].addItems(refactored_items_list)

    newLength = len(refactored_items_list)
    
    print("refactored_items_list: ",refactored_items_list)

    if multi_path_box_type == "customBulkAddFilePaths":
        self.form.widget.state = {
            property: refactored_items_list
        }
    elif multi_path_box_type == "customBulkAddMultiLikeFilePaths": 
        collectProperty = save_dict[property]["collect_property"]
        self.form.widget.state = {
            property: refactored_items_list[0],
            collectProperty: refactored_items_list
        }

    if multi_path_box_type == "customBulkAddFilePaths":
        if oldLength:
            if ((oldLength > 0) and (newLength == 0)):
                print("hide")
                
                save_dict[property]["lbl"].hide()
                save_dict[property]["add_files_box"].hide()

    if multi_path_box_type == "customBulkAddMultiLikeFilePaths":
        if newLength > 1:
            print("show")
            indices = [i for i, x in enumerate(self.priorityContentList) if ("multiple like resource" in x) and ("permanent hide" not in x)]
            print(indices)
            for i in indices:
                labelW = self.formLabelWidgetList[i]
                print(labelW)
                labelWType = self.formLabelWidgetTypeList[i]
                print(labelWType)
                labelWText = self.formLabelWidgetTextList[i]
                print(labelWText)
                fieldW = self.formWidgetList[i]
                print(fieldW)
                fieldWName = self.formWidgetNameList[i]
                print(fieldWName)

                labelW.show()
                fieldW.show()

            save_dict[property]["lbl_applyNameConvention"].show()
            save_dict[property]["btn_applyNameConvention"].show()

        if oldLength:
            if ((oldLength > 1) and (newLength <= 1)):
                print("hide")
                indices = [i for i, x in enumerate(self.priorityContentList) if "multiple like resource" in x]
                print(indices)
                for i in indices:
                    labelW = self.formLabelWidgetList[i]
                    print(labelW)
                    labelWType = self.formLabelWidgetTypeList[i]
                    print(labelWType)
                    labelWText = self.formLabelWidgetTextList[i]
                    print(labelWText)
                    fieldW = self.formWidgetList[i]
                    print(fieldW)
                    fieldWName = self.formWidgetNameList[i]
                    print(fieldWName)

                    labelW.hide()
                    fieldW.hide()
                    # should also probably delete the contents of these folders?

                save_dict[property]["lbl_applyNameConvention"].hide()
                save_dict[property]["btn_applyNameConvention"].hide()
            
def toggle_add_file_box_visibility(property,label,add_files_box,self):
    property = property
    print("property in toggle fx: ",property)

    if ((label.isHidden()) and (add_files_box.isHidden())):
        label.show()
        add_files_box.show()
    else:
        label.hide()
        add_files_box.hide()

